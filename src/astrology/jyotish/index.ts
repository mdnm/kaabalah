export type NakshatraFrame = "dhruva" | "lahiri";

export interface JyotishChartInput {
  /** UT instant of birth. */
  date: Date;
  latitude: number;
  longitude: number;
  /** Frame for nakshatras/dashas. Default "dhruva". */
  nakshatraFrame?: NakshatraFrame;
  /** Node convention for Rahu/Ketu and the 8-karaka scheme. Default "mean". */
  node?: NodeConvention;
  /** Dasha year length in days. Default 365.2422 (dhruva) or 365.25 (lahiri reference). */
  yearLengthDays?: number;
  /** 7 (default) or 8. */
  karakaScheme?: KarakaScheme;
  /** Frame of the karaka degrees. Default: tropical for dhruva, sidereal for lahiri. */
  karakaDegreeFrame?: KarakaDegreeFrame;
  /** Default true. Untimed: no Moon, lagna, karakas, or dashas. */
  timed?: boolean;
  ephemeris?: JyotishEphemeris;
  /**
   * Throw `SwissEphEphemerisMismatchError` if Swiss Ephemeris substitutes another ephemeris
   * (for example Moshier outside the installed .se1 range). Default false: the substitution is
   * then reported in `ephemerisUsage` instead of being silent.
   */
  strictEphemeris?: boolean;
  /** Exclusive end of dasha generation; default one full cycle. */
  through?: Date;
}

export interface JyotishChart {
  method: typeof JYOTISH_METHODS;
  nakshatraFrame: NakshatraFrame;
  node: NodeConvention;
  /** Always computed: tropical rasis/longitudes live on each point (`tropical`). */
  dhruva: DhruvaChart;
  lahiri: LahiriChart;
  karakas?: KarakaResult;
  vimshottari?: DashaSchedule;
  yogini?: DashaSchedule;
  yearLengthDays: number;
  /** Ephemeris actually used by both frames combined (see `EphemerisUsage`). */
  ephemerisUsage: EphemerisUsage;
}

/** Top-level convenience: both frames are computed, dashas/karakas follow the selected one. */
export function getJyotishChart(input: JyotishChartInput): JyotishChart {
  const nakshatraFrame = input.nakshatraFrame ?? "dhruva";
  const node = input.node ?? "mean";
  const timed = input.timed !== false;
  const ephemeris = input.ephemeris ?? "swiss";
  const yearLengthDays =
    input.yearLengthDays ??
    (nakshatraFrame === "dhruva" ? DASHA_YEAR_LENGTH_REFERENCES.dhruva : DASHA_YEAR_LENGTH_REFERENCES.lahiriReference);
  const base = {
    date: input.date,
    latitude: input.latitude,
    longitude: input.longitude,
    node,
    timed,
    ephemeris,
    strictEphemeris: input.strictEphemeris,
  };
  const dhruva = calculateDhruvaChart(base);
  const lahiri = calculateLahiriChart(base);

  const result: JyotishChart = {
    method: JYOTISH_METHODS,
    nakshatraFrame,
    node,
    dhruva,
    lahiri,
    yearLengthDays,
    ephemerisUsage: mergeEphemerisUsage(dhruva.ephemerisUsage, lahiri.ephemerisUsage),
  };
  if (!timed) return result;

  const karakaFrame: KarakaDegreeFrame = input.karakaDegreeFrame ?? (nakshatraFrame === "dhruva" ? "tropical" : "sidereal");
  const bodies: KarakaBody[] = ["sun", "moon", "mars", "mercury", "jupiter", "venus", "saturn", "rahu"];
  const karakaInputs: KarakaInput[] = bodies.map((body) => {
    const p: DhruvaPoint | LahiriPoint | undefined =
      karakaFrame === "tropical" ? dhruva.points[body] : lahiri.points[body];
    if (!p) throw new Error(`Missing point ${body}`);
    const degreeInSign = karakaFrame === "tropical" ? (p as DhruvaPoint).tropical.degreeInSign : (p as LahiriPoint).sidereal.degreeInSign;
    return { body, degreeInSign };
  });
  const scheme = input.karakaScheme ?? 7;
  result.karakas = calculateCharaKarakas(karakaInputs, { scheme, degreeFrame: karakaFrame, node });

  const moon = nakshatraFrame === "dhruva" ? dhruva.points.moon : lahiri.points.moon;
  if (moon) {
    const common = {
      birth: input.date,
      moonNakshatraIndex: moon.nakshatraIndex,
      moonElapsedFraction: moon.elapsedFraction,
      yearLengthDays,
      through: input.through,
    };
    result.vimshottari = generateDashaSchedule({ ...common, system: "vimshottari" });
    result.yogini = generateDashaSchedule({ ...common, system: "yogini" });
  }
  return result;
}
